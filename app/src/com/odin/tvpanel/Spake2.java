package com.odin.tvpanel;

import java.math.BigInteger;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.security.SecureRandom;

/**
 * SPAKE2 over edwards25519, byte-for-byte compatible with BoringSSL's SPAKE2
 * (crypto/curve25519/spake25519.cc, Apache-2.0), which Android's
 * "Wireless debugging" pairing uses. Written from the BoringSSL source; plain
 * BigInteger arithmetic is fine here because pairing runs once.
 *
 * Not constant time. The secret is a one-time 6-digit pairing code that is
 * useless after pairing, and this code runs on the TV itself.
 */
final class Spake2 {
    static final int ALICE = 0, BOB = 1;

    private static final BigInteger P = BigInteger.ONE.shiftLeft(255).subtract(BigInteger.valueOf(19));
    private static final BigInteger D = BigInteger.valueOf(-121665)
            .multiply(BigInteger.valueOf(121666).modInverse(P)).mod(P);
    private static final BigInteger D2 = D.shiftLeft(1).mod(P);
    private static final BigInteger SQRT_M1 = BigInteger.valueOf(2)
            .modPow(P.subtract(BigInteger.ONE).shiftRight(2), P);
    /** Order of the prime-order subgroup. */
    static final BigInteger L = BigInteger.ONE.shiftLeft(252)
            .add(new BigInteger("27742317777372353535851937790883648493"));

    private static final Point B = decode(hex("5866666666666666666666666666666666666666666666666666666666666666"));
    // Generated by BoringSSL from SHA-256 of "edwards25519 point generation seed (M|N)".
    private static final Point M = decode(hex("5ada7e4bf6ddd9adb6626d32131c6b5c51a1e347a3478f53cfcf441b88eed12e"));
    private static final Point N = decode(hex("10e3df0ae37d8e7a99b5fe74b44672103dbddcbd06af680d71329a11693bc778"));

    private final int role;
    private final byte[] myName, theirName;
    private BigInteger privateKey, passwordScalar;
    private byte[] passwordHash, myMsg;

    Spake2(int role, byte[] myName, byte[] theirName) {
        this.role = role;
        this.myName = myName;
        this.theirName = theirName;
    }

    byte[] generateMsg(byte[] password) {
        byte[] r = new byte[64];
        new SecureRandom().nextBytes(r);
        return generateMsg(password, r);
    }

    /** Deterministic variant (random input supplied) so it can be checked against BoringSSL vectors. */
    byte[] generateMsg(byte[] password, byte[] random64) {
        // private = 8 * (random mod L): multiplying by the cofactor clears small-order parts later.
        privateKey = le(random64).mod(L).shiftLeft(3);
        Point pub = B.mul(privateKey);

        passwordHash = sha512(password);
        BigInteger s = le(passwordHash).mod(L);
        // BoringSSL "password scalar hack": add multiples of L until the scalar is a multiple of 8.
        if (s.testBit(0)) s = s.add(L);
        if (s.testBit(1)) s = s.add(L.shiftLeft(1));
        if (s.testBit(2)) s = s.add(L.shiftLeft(2));
        passwordScalar = s;

        Point mask = (role == ALICE ? M : N).mul(passwordScalar);
        myMsg = pub.add(mask).encode();
        return myMsg.clone();
    }

    /** Returns the 64-byte shared key, or null if the peer's message is not a valid point. */
    byte[] processMsg(byte[] theirMsg) {
        if (myMsg == null || theirMsg == null || theirMsg.length != 32) return null;
        Point q = decode(theirMsg);
        if (q == null) return null;
        Point peersMask = (role == ALICE ? N : M).mul(passwordScalar);
        Point dh = q.add(peersMask.negate()).mul(privateKey);
        byte[] dhEnc = dh.encode();

        MessageDigest sha = digest("SHA-512");
        if (role == ALICE) {
            lp(sha, myName);
            lp(sha, theirName);
            lp(sha, myMsg);
            lp(sha, theirMsg);
        } else {
            lp(sha, theirName);
            lp(sha, myName);
            lp(sha, theirMsg);
            lp(sha, myMsg);
        }
        lp(sha, dhEnc);
        lp(sha, passwordHash);
        return sha.digest();
    }

    private static void lp(MessageDigest sha, byte[] data) {
        long l = data.length;
        for (int i = 0; i < 8; i++) {
            sha.update((byte) l);
            l >>>= 8;
        }
        sha.update(data);
    }

    // ---- edwards25519, extended coordinates (X:Y:Z:T), x = X/Z, y = Y/Z, xy = T/Z ----

    static final class Point {
        final BigInteger x, y, z, t;

        Point(BigInteger x, BigInteger y, BigInteger z, BigInteger t) {
            this.x = x;
            this.y = y;
            this.z = z;
            this.t = t;
        }

        static Point identity() {
            return new Point(BigInteger.ZERO, BigInteger.ONE, BigInteger.ONE, BigInteger.ZERO);
        }

        /** Complete addition (RFC 8032 section 5.1.4). */
        Point add(Point q) {
            BigInteger a = y.subtract(x).multiply(q.y.subtract(q.x)).mod(P);
            BigInteger b = y.add(x).multiply(q.y.add(q.x)).mod(P);
            BigInteger c = t.multiply(D2).multiply(q.t).mod(P);
            BigInteger d = z.shiftLeft(1).multiply(q.z).mod(P);
            BigInteger e = b.subtract(a), f = d.subtract(c), g = d.add(c), h = b.add(a);
            return new Point(e.multiply(f).mod(P), g.multiply(h).mod(P), f.multiply(g).mod(P), e.multiply(h).mod(P));
        }

        Point negate() {
            return new Point(P.subtract(x).mod(P), y, z, P.subtract(t).mod(P));
        }

        /** Exact integer scalar (not reduced mod L): the small-order part matters for M and N. */
        Point mul(BigInteger k) {
            Point r = identity();
            for (int i = k.bitLength() - 1; i >= 0; i--) {
                r = r.add(r);
                if (k.testBit(i)) r = r.add(this);
            }
            return r;
        }

        byte[] encode() {
            BigInteger zi = z.modInverse(P);
            BigInteger ax = x.multiply(zi).mod(P), ay = y.multiply(zi).mod(P);
            byte[] out = toLe(ay);
            if (ax.testBit(0)) out[31] |= (byte) 0x80;
            return out;
        }
    }

    /** Point decoding as in BoringSSL's x25519_ge_frombytes_vartime; null if not on the curve. */
    static Point decode(byte[] s) {
        byte[] c = s.clone();
        boolean sign = (c[31] & 0x80) != 0;
        c[31] &= 0x7f;
        BigInteger y = le(c).mod(P);
        BigInteger y2 = y.multiply(y).mod(P);
        BigInteger u = y2.subtract(BigInteger.ONE).mod(P);
        BigInteger v = D.multiply(y2).add(BigInteger.ONE).mod(P);
        BigInteger x2 = u.multiply(v.modInverse(P)).mod(P);
        BigInteger x = x2.modPow(P.add(BigInteger.valueOf(3)).shiftRight(3), P);
        if (!x.multiply(x).mod(P).equals(x2)) {
            x = x.multiply(SQRT_M1).mod(P);
            if (!x.multiply(x).mod(P).equals(x2)) return null;
        }
        if (x.testBit(0) != sign) x = P.subtract(x).mod(P);
        return new Point(x, y, BigInteger.ONE, x.multiply(y).mod(P));
    }

    // ---- helpers ----

    static BigInteger le(byte[] b) {
        byte[] be = new byte[b.length + 1];
        for (int i = 0; i < b.length; i++) be[be.length - 1 - i] = b[i];
        return new BigInteger(be);
    }

    static byte[] toLe(BigInteger v) {
        byte[] be = v.toByteArray();
        byte[] out = new byte[32];
        for (int i = 0; i < 32 && i < be.length; i++) out[i] = be[be.length - 1 - i];
        return out;
    }

    static byte[] sha512(byte[] in) {
        return digest("SHA-512").digest(in);
    }

    private static MessageDigest digest(String alg) {
        try {
            return MessageDigest.getInstance(alg);
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    static byte[] hex(String s) {
        byte[] b = new byte[s.length() / 2];
        for (int i = 0; i < b.length; i++) b[i] = (byte) Integer.parseInt(s.substring(2 * i, 2 * i + 2), 16);
        return b;
    }
}
